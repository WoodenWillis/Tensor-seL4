static volatile uint32_t *g_decon;
static volatile uint32_t *g_fb;
static uint32_t g_w, g_h, g_stride_w;   /* stride in 32-bit words */
static uint32_t g_cols, g_rows;         /* text grid size in glyph cells */
static uint32_t g_col, g_row;           /* cursor */
static char *g_grid;                    /* g_cols * g_rows text backing store */
static int g_ok;
static write_buf_fn g_prev_write;

static inline void px_block(uint32_t x, uint32_t y, uint32_t color)
{
    for (uint32_t dy = 0; dy < SCALE; dy++) {
        volatile uint32_t *row = g_fb + (size_t)(y + dy) * g_stride_w + x;
        for (uint32_t dx = 0; dx < SCALE; dx++) {
            row[dx] = color;
        }
    }
}

static void draw_glyph(uint32_t col, uint32_t row, unsigned char c)
{
    const uint8_t *gl = (c >= 0x20 && c < 0x80) ? font8x8[c - 0x20] : font8x8[0];
    uint32_t x0 = col * GW, y0 = row * GH;
    for (uint32_t gy = 0; gy < 8; gy++) {
        uint8_t bits = gl[gy];
        for (uint32_t gx = 0; gx < 8; gx++) {
            px_block(x0 + gx * SCALE, y0 + gy * SCALE, (bits >> gx) & 1u ? FG : BG);
        }
    }
}

static void present(void)
{
    uint32_t t = g_decon[DECON_TRIG_CON / 4];
    g_decon[DECON_TRIG_CON / 4] =
        (t & ~(TRIG_CON_HW_TRIG_EN | TRIG_CON_HW_TRIG_MASK))
        | TRIG_CON_SW_TRIG_EN | TRIG_CON_SW_TRIG_DET_EN;
    __atomic_thread_fence(__ATOMIC_SEQ_CST);
    g_decon[DECON_SHD_REG_UP_REQ / 4] = SHD_REG_UP_REQ_GLOBAL;
    __atomic_thread_fence(__ATOMIC_SEQ_CST);
}

static void redraw_all(void)
{
    for (uint32_t r = 0; r < g_rows; r++) {
        for (uint32_t c = 0; c < g_cols; c++) {
            draw_glyph(c, r, (unsigned char) g_grid[(size_t) r * g_cols + c]);
        }
    }
}

static void scroll_up(void)
{
    memmove(g_grid, g_grid + g_cols, (size_t)(g_rows - 1) * g_cols);
    memset(g_grid + (size_t)(g_rows - 1) * g_cols, ' ', g_cols);
    redraw_all();
    g_row = g_rows - 1;
    g_col = 0;
}

static void newline(void)
{
    g_col = 0;
    if (++g_row >= g_rows) {
        scroll_up();
    }
}

static void put(char ch)
{
    unsigned char c = (unsigned char) ch;
    if (c == '\n') {
        newline();
        return;
    }
    if (c == '\r') {
        g_col = 0;
        return;
    }
    if (c == '\t') {
        for (int i = 0; i < 4; i++) {
            put(' ');
        }
        return;
    }
    if (c < 0x20 || c > 0x7e) {
        return;   /* skip other control / non-ASCII */
    }
    if (g_col >= g_cols) {
        newline();
    }
    g_grid[(size_t) g_row * g_cols + g_col] = (char) c;
    draw_glyph(g_col, g_row, c);
    g_col++;
}

/* muslcsys stdout tee: mirror to UART (previous handler) and the panel */
static size_t fbcon_write(void *data, size_t count)
{
    if (g_prev_write) {
        g_prev_write(data, count);
    }
    if (g_ok) {
        const char *s = (const char *) data;
        for (size_t i = 0; i < count; i++) {
            put(s[i]);
        }
        present();
    }
    return count;
}

int fbcon_init(void)
{
    g_decon = (volatile uint32_t *) ps_io_map(&env.ops.io_mapper, DECON0_BASE, 0x1000, 0, PS_MEM_NORMAL);
    volatile uint32_t *rdma =
        (volatile uint32_t *) ps_io_map(&env.ops.io_mapper, DPU_RDMA0_BASE, 0x1000, 0, PS_MEM_NORMAL);
    if (g_decon == NULL || rdma == NULL) {
        return -1;
    }

    uint32_t img    = rdma[RDMA_IMG_SIZE / 4];
    uint32_t fbp    = rdma[RDMA_BASEADDR_P0 / 4];
    uint32_t stride = rdma[RDMA_SRC_STRIDE_0 / 4] & 0x00FFFFFFu;
    g_w = img & 0xFFFFu;
    g_h = (img >> 16) & 0xFFFFu;
    if (fbp == 0 || g_w == 0 || g_h == 0) {
        return -1;
    }
    if (stride == 0) {
        stride = g_w * 4u;
    }
    g_stride_w = stride / 4u;

    size_t map_bytes = (size_t) stride * g_h;
    if (map_bytes > FB_MAP_MAX) {
        map_bytes = FB_MAP_MAX;
    }
    g_fb = (volatile uint32_t *) ps_io_map(&env.ops.io_mapper, fbp, map_bytes, 0, PS_MEM_NORMAL);
    if (g_fb == NULL) {
        return -1;
    }
    uint32_t mapped_rows = (uint32_t)(map_bytes / stride);

    g_cols = g_w / GW;
    g_rows = mapped_rows / GH;
    g_grid = malloc((size_t) g_cols * g_rows);
    if (g_grid == NULL) {
        return -1;
    }
    memset(g_grid, ' ', (size_t) g_cols * g_rows);
    g_col = g_row = 0;

    /* Clear the whole mapped framebuffer to black */
    for (size_t i = 0; i < map_bytes / 4; i++) {
        g_fb[i] = BG;
    }

    /* DECON command-mode start */

    uint32_t g = g_decon[DECON_GLOBAL_CON / 4];
    g_decon[DECON_GLOBAL_CON / 4] = g | GLOBAL_CON_DECON_EN | GLOBAL_CON_DECON_EN_F;
    __atomic_thread_fence(__ATOMIC_SEQ_CST);
    g_decon[DECON_SHD_REG_UP_REQ / 4] = SHD_REG_UP_REQ_GLOBAL;
    __atomic_thread_fence(__ATOMIC_SEQ_CST);
    for (uint32_t spins = 0;
         !(g_decon[DECON_GLOBAL_CON / 4] & GLOBAL_CON_RUN_STATUS) && spins < 2000000u;
         spins++) {
    }

    g_ok = 1;
    present();

    g_prev_write = sel4muslcsys_register_stdio_write_fn(fbcon_write);
    return 0;
}
